#!/usr/bin/env python3
"""Run every detection, enrich the source IPs and write a triage summary.

Usage:  python3 -m automation.run_triage
"""
import argparse
import json
from pathlib import Path

from .cloudtrail_detections import suspicious_key_use
from .common import load_jsonl
from .enrich_ip import enrich, load_blocklist
from .okta_detections import impossible_travel, mfa_fatigue
from .windows_detections import detect_bruteforce

ROOT = Path(__file__).resolve().parent.parent

ACTIONS = {
    "windows_bruteforce_then_success": [
        "Disable the compromised account and force a password reset",
        "Isolate the host and review every process and account change after the logon",
        "Block the source IP at the firewall and search for it in all other logs",
        "Remove the account created by the attacker; check persistence"],
    "windows_bruteforce": [
        "Block the source IP; confirm no later successful logon exists",
        "Check that the targeted accounts have lockout and MFA enabled"],
    "okta_impossible_travel": [
        "Contact the user to confirm both logins; if not both theirs, revoke sessions and reset the password",
        "Check what the second session accessed"],
    "okta_mfa_push_fatigue": [
        "Treat the account as compromised: revoke sessions, reset password and MFA factors",
        "Block the source IP; check what the session accessed after the approved push"],
    "aws_access_key_new_ip_sensitive_actions": [
        "Deactivate the access key now, then rotate it",
        "Delete the attacker-created user and keys; review CloudTrail for everything the key did",
        "Find how the key leaked (repo, CI logs, laptop) and fix that"],
}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default=ROOT / "data/sample")
    ap.add_argument("--out", default=ROOT / "reports")
    args = ap.parse_args()
    data, out = Path(args.data), Path(args.out)
    out.mkdir(exist_ok=True)
    bl = load_blocklist(ROOT / "data/threat_intel/blocklist.csv")

    alerts = []
    alerts += detect_bruteforce(load_jsonl(data / "windows_security.json"))
    okta = load_jsonl(data / "okta_system.json")
    alerts += impossible_travel(okta) + mfa_fatigue(okta)
    alerts += suspicious_key_use(load_jsonl(data / "cloudtrail.json"))

    lines = ["# Triage summary (generated by automation/run_triage.py)", "",
             f"Alerts raised: **{len(alerts)}**", ""]
    for n, a in enumerate(alerts, 1):
        a["enrichment"] = enrich(a["source_ip"], bl)
        a["recommended_actions"] = ACTIONS[a["rule"]]
        tag = f" ({a['enrichment']['intel_tag']})" if a["enrichment"]["intel_tag"] else ""
        lines += [f"## {n}. {a['rule']} ({a['severity'].upper()})", "",
                  f"- Source IP: `{a['source_ip']}` -> {a['enrichment']['verdict']}{tag}",
                  f"- MITRE ATT&CK: {', '.join(a['mitre'])}"]
        for k, v in a.items():
            if k not in ("rule", "severity", "source_ip", "enrichment", "mitre",
                         "recommended_actions", "follow_on_activity"):
                lines.append(f"- {k}: {v}")
        for f in a.get("follow_on_activity", []):
            lines.append(f"- follow-on: {f['time']} ({f['event']}) {f['detail']}")
        lines += ["", "Recommended actions:"] + [f"1. {x}" for x in a["recommended_actions"]] + [""]
    (out / "triage_summary.md").write_text("\n".join(lines), encoding="utf-8")
    (out / "alerts.json").write_text(json.dumps(alerts, indent=2), encoding="utf-8")
    print(f"{len(alerts)} alerts -> {out / 'triage_summary.md'}")
    for a in alerts:
        print(f"  [{a['severity'].upper():6}] {a['rule']}  {a['source_ip']}  "
              f"{a['enrichment']['verdict']}")


if __name__ == "__main__":
    main()
